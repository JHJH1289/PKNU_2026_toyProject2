-- Oracle schema for Travel Planner saved plans.
-- Run as the application schema owner.

CREATE TABLE TRAVEL_PLANS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_ID VARCHAR2(50 CHAR) NOT NULL,
    TITLE VARCHAR2(300 CHAR) NOT NULL,
    SUMMARY VARCHAR2(2000 CHAR),
    REGION VARCHAR2(200 CHAR),
    PLAN_STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    GENERATED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_TRAVEL_PLAN_STATUS
        CHECK (PLAN_STATUS IN ('DRAFT', 'GENERATED'))
);

CREATE TABLE TRAVEL_PLAN_PLACES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLAN_ID NUMBER NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    PLACE_NAME VARCHAR2(300 CHAR) NOT NULL,
    PLACE_KIND VARCHAR2(30 CHAR) NOT NULL,
    ADDRESS VARCHAR2(1000 CHAR),
    LATITUDE NUMBER(10, 7),
    LONGITUDE NUMBER(10, 7),
    CONSTRAINT FK_TRAVEL_PLAN_PLACES_PLAN
        FOREIGN KEY (PLAN_ID)
        REFERENCES TRAVEL_PLANS (ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_TRAVEL_PLAN_PLACE_KIND
        CHECK (PLACE_KIND IN ('ATTRACTION', 'RESTAURANT'))
);

CREATE TABLE TRAVEL_PLAN_STEPS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLAN_ID NUMBER NOT NULL,
    SORT_ORDER NUMBER DEFAULT 0 NOT NULL,
    STEP_TIME VARCHAR2(30 CHAR),
    PLACE_NAME VARCHAR2(300 CHAR),
    THEME VARCHAR2(100 CHAR),
    NOTE VARCHAR2(2000 CHAR),
    CONSTRAINT FK_TRAVEL_PLAN_STEPS_PLAN
        FOREIGN KEY (PLAN_ID)
        REFERENCES TRAVEL_PLANS (ID)
        ON DELETE CASCADE
);

CREATE INDEX IX_TRAVEL_PLANS_OWNER_CREATED
    ON TRAVEL_PLANS (OWNER_ID, CREATED_AT DESC);

CREATE INDEX IX_TRAVEL_PLAN_PLACES_PLAN_ORDER
    ON TRAVEL_PLAN_PLACES (PLAN_ID, SORT_ORDER);

CREATE INDEX IX_TRAVEL_PLAN_STEPS_PLAN_ORDER
    ON TRAVEL_PLAN_STEPS (PLAN_ID, SORT_ORDER);

ALTER TABLE TRAVEL_PLANS
    ADD CONSTRAINT FK_TRAVEL_PLANS_OWNER
    FOREIGN KEY (OWNER_ID)
    REFERENCES USERS (USERNAME);

